/*
 * sw2e_mem.h - the PS2 memory model of the port (see docs/port.md).
 *
 * The game keeps 32-bit PS2 addresses in its data: in tables of the boot executable, in heap
 * structures, in lists, in the save image. On the PS2 an address is a pointer. On the PC (64-bit)
 * the whole EE RAM is one 32 MB block. The boot executable's data is loaded at its PS2 addresses
 * inside it, and an address stored in game data stays a 32-bit PS2 address. Native pointers only
 * live in C locals and parameters.
 *
 *   ps2ptr          a 32-bit PS2 address stored in game data (a field, a global, a table entry)
 *   PS2_PTR(a)      the native pointer for PS2 address `a`
 *   PS2_ADDR(p)     the PS2 address of native pointer `p` (which must point into PS2 memory)
 *   PS2_FUNC(a)     the PC function for code address `a`; PS2_CODE(f) the code address of function f
 *   PS2_GETP(T, a)  the pointer stored at PS2 address `a`, as type T; PS2_SETP(a, v) stores one
 *
 * On the PS2 build (CodeWarrior, matching) both are plain casts, so the generated code does not
 * change. The PC build defines SW2E_PC.
 *
 * It uses only the basic C types, so it can be included anywhere.
 */

#ifndef SW2E_MEM_H
#define SW2E_MEM_H

typedef unsigned int ps2ptr;

/* An integer as wide as a native pointer, for alignment arithmetic on pointers ((u32)p on the
 * PS2 would cut a PC pointer to 32 bits). Plain unsigned int on the PS2 build. */
#ifdef SW2E_PC
typedef unsigned long long sw2e_uptr;
#else
typedef unsigned int sw2e_uptr;
#endif

#ifdef SW2E_PC

/* the EE kernel calls under PC names (some PS2 names are also Windows kernel32 functions) */
#include "sw2e_ee_kernel.h"

#define PS2_RAM_SIZE 0x02000000u         /* 32 MB of EE RAM */
#define PS2_SPR_BASE 0x70000000u         /* the scratchpad, 16 KB */
#define PS2_SPR_SIZE 0x4000u

#define PS2_HW_BASE  0x10000000u         /* EE hardware registers (timers, DMA, VIF, GIF...), 64 KB */
#define PS2_HW_SIZE  0x10000u
#define PS2_GS_BASE  0x12000000u         /* GS privileged registers, 8 KB */
#define PS2_GS_SIZE  0x2000u

extern unsigned char *sw2e_ram;                     /* the PS2 RAM block, allocated by the port */
extern unsigned char *sw2e_spr;                     /* the scratchpad */
extern unsigned char *sw2e_hw;                      /* stand-ins for the hardware registers */
extern unsigned char *sw2e_gs;

/* PC data outside the blocks (string literals of the PC build, the port's own buffers) that the
 * game stores as a PS2 address: each gets a 64 KB window at 0x50000000 + index * 0x10000
 * (port/sw2e/sw2e_entry.c). */
#define PS2_FOREIGN_BASE 0x50000000u
void *sw2e_foreign_ptr(unsigned int a);
unsigned int sw2e_foreign_addr(const void *p);

/* The native pointer for PS2 address `a` (RAM mirrors at 0x20000000/0x30000000 included).
 * Hardware registers get blocks of their own, which the port reads where it replaces the
 * hardware (DMA, GS), so a register write never lands in the RAM. */
static inline void *sw2e_ptr(unsigned int a)
{
    if (a == 0)
        return (void *)0;
    if ((a & 0xF0000000u) == PS2_SPR_BASE)
        return sw2e_spr + (a & (PS2_SPR_SIZE - 1));
    if ((a & 0xFFFF0000u) == PS2_HW_BASE)
        return sw2e_hw + (a & (PS2_HW_SIZE - 1));
    if ((a & 0xFFFFE000u) == PS2_GS_BASE)
        return sw2e_gs + (a & (PS2_GS_SIZE - 1));
    if ((a & 0xF0000000u) == PS2_FOREIGN_BASE)
        return sw2e_foreign_ptr(a);
    return sw2e_ram + (a & (PS2_RAM_SIZE - 1));
}

/* The PS2 address of native pointer `p`, which must point into one of the blocks above. */
static inline unsigned int sw2e_addr(const void *p)
{
    const unsigned char *q = (const unsigned char *)p;

    if (q == 0)
        return 0;
    if (q >= sw2e_spr && q < sw2e_spr + PS2_SPR_SIZE)
        return PS2_SPR_BASE + (unsigned int)(q - sw2e_spr);
    if (q >= sw2e_hw && q < sw2e_hw + PS2_HW_SIZE)
        return PS2_HW_BASE + (unsigned int)(q - sw2e_hw);
    if (q >= sw2e_gs && q < sw2e_gs + PS2_GS_SIZE)
        return PS2_GS_BASE + (unsigned int)(q - sw2e_gs);
    if (q >= sw2e_ram && q < sw2e_ram + PS2_RAM_SIZE)
        return (unsigned int)(q - sw2e_ram);
    return sw2e_foreign_addr(q);
}

#define PS2_PTR(a) sw2e_ptr((unsigned int)(a))
#define PS2_ADDR(p) sw2e_addr(p)
/* A global at a fixed PS2 address (used by the PC build's rewritten declarations). */
#define PS2_MEM(a) ((unsigned char *)sw2e_ptr(a))

/* Code addresses stored in PS2 data (function tables): the PC function for PS2 address `a`
 * (from the functions' address tags), and a view of `n` table entries at `a` as PC function
 * pointers (n = 0: up to 256). Generated by tools/pc_build.py. */
void *sw2e_func(unsigned int a);
void *const *sw2e_fntab(unsigned int a, int n);
unsigned int sw2e_code_addr(void *fn);
/* For macros that receive either a native pointer or a PS2 address held in an integer. */
#define PS2_ANYPTR(o) _Generic((o),     int: sw2e_ptr((unsigned int)(sw2e_uptr)(o)), unsigned int: sw2e_ptr((unsigned int)(sw2e_uptr)(o)),     long long: sw2e_ptr((unsigned int)(sw2e_uptr)(o)), unsigned long long: sw2e_ptr((unsigned int)(sw2e_uptr)(o)),     default: (void *)(sw2e_uptr)(o))
#define PS2_FUNC(a) sw2e_func((unsigned int)(a))
#define PS2_CODE(f) sw2e_code_addr((void *)(f))

#else /* the PS2 build */

#define PS2_PTR(a) ((void *)(a))
#define PS2_ADDR(p) ((unsigned int)(p))
#define PS2_ANYPTR(o) ((void *)(o))
#define PS2_FUNC(a) ((void *)(a))
#define PS2_CODE(f) ((unsigned int)(f))

#endif

/* A pointer stored in PS2 memory at address `a` (4 bytes on the PS2, so never read or written as
 * a native pointer): its value as type T, and storing pointer `v` there. Same code on the PS2. */
#define PS2_GETP(T, a) ((T)PS2_PTR(*(ps2ptr *)PS2_PTR(a)))
#define PS2_SETP(a, v) (*(ps2ptr *)PS2_PTR(a) = PS2_ADDR(v))

#endif
